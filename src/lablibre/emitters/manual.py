"""
Manual emitter: writes a plan as a Markdown protocol for a person at the bench.

The same plan and planner that drive the robots decide which pipette to use,
when to change tips, where one aspiration can serve several wells, and how to
split large volumes. This emitter only phrases those decisions for a human:
an equipment list, reagents to prepare, and numbered steps with a table of
transfers per step.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

from lablibre.bundle import Bundle, FileRole
from lablibre.emitters.base import Emitter, format_number, slugify
from lablibre.labware import Labware, WellRef
from lablibre.modules import ModuleKind
from lablibre.ops import DistributePass, HeadLayout, MixReduced, PickUpTips, TransferPass, TransferPlan
from lablibre.plan import Plan
from lablibre.planner import ChannelPlanner
from lablibre.profile import RobotProfile
from lablibre.steps import (OFF_DECK, Comment, Delay, MoveLabware, Ordering, Pause, SetLid, SetTemperature,
                            Step, ThermalProfile, TipPolicy, Transfer, TransferSet)

_MODULE_NAMES = {
    ModuleKind.TEMPERATURE: "temperature block",
    ModuleKind.THERMOCYCLER: "thermocycler",
    ModuleKind.HEATER_SHAKER: "heater-shaker",
    ModuleKind.MAGNETIC: "magnetic rack",
}

_TIP_POLICIES = {
    TipPolicy.NEW_EACH: "Use a fresh tip for every transfer.",
    TipPolicy.PER_SOURCE: "Keep the same tip while drawing from the same source.",
    TipPolicy.ONE: "Use one tip for the whole step.",
}


@dataclass
class _Row:
    """One line of a step's transfer table."""
    new_tip: bool
    pipette: str
    source: str
    dest: str
    volume: float
    parts: int = 1  # how many aspirations the volume is split into
    notes: List[str] = field(default_factory=list)
    key: Tuple = ()  # identifies a transfer whose later parts should merge into this row
    volume_text: Optional[str] = None


class ManualEmitter(Emitter):
    """
    Compile a plan into a Markdown bench protocol.

    The bundle contains ``<name>_bench_protocol.md`` and ``<name>_plan.json``.
    Profiles for this emitter use ``robot: "manual"``; their labware map gives
    human-readable names (``"plate_96": "96-well PCR plate"``) and liquid
    classes may carry a ``note`` shown on steps that handle that liquid.
    """

    robots = ("manual",)

    def compile(self, plan: Plan, profile: RobotProfile) -> Bundle:
        self._check_profile(profile)
        plan_warnings = plan.check()
        planned = ChannelPlanner(profile, plan).plan_all()
        slug = slugify(plan.name)
        bundle = Bundle(target=profile.name, warnings=self._warnings(plan, plan_warnings, planned))
        bundle.add(f"{slug}_bench_protocol.md", self._render(plan, profile, planned, bundle.warnings),
                   FileRole.PROTOCOL)
        bundle.add(f"{slug}_plan.json", json.dumps(plan.to_dict(), indent=2) + "\n", FileRole.DATA)
        return bundle

    # --- document --------------------------------------------------------------------------

    def _render(self, plan: Plan, profile: RobotProfile, planned: Dict[int, TransferPlan], warnings: List[str]) -> str:
        lines = [f"# {plan.name}: bench protocol", ""]
        if plan.description:
            lines += [plan.description, ""]
        lines += [f"_Generated by LabLibre for **{profile.name}**._", ""]
        lines += self._equipment(plan, profile, planned)
        lines += self._reagents(plan)
        if warnings:
            lines += ["## Warnings", "", "Check these before you start:", ""] + [f"- {w}" for w in warnings] + [""]
        lines += ["## Procedure", ""]
        number = 0
        for index, step in enumerate(plan.steps):
            body = self._step(plan, profile, step, planned.get(index))
            if body is None:
                continue
            number += 1
            title, *rest = body
            lines += [f"### {number}. {title}", ""] + (rest + [""] if rest else [])
        return "\n".join(lines).rstrip() + "\n"

    def _equipment(self, plan: Plan, profile: RobotProfile, planned: Dict[int, TransferPlan]) -> List[str]:
        tips: Dict[str, int] = {}
        for transfer_plan in planned.values():
            for name, count in transfer_plan.tips_used().items():
                tips[name] = tips.get(name, 0) + count
        lines = ["## Equipment", ""]
        if tips:
            lines += ["**Pipettes**", ""]
            for spec in profile.pipettes:
                if spec.name in tips:
                    channels = f", {spec.channels}-channel" if spec.is_multichannel else ""
                    lines.append(f"- {spec.name} ({format_number(spec.min_volume)}–{format_number(spec.max_volume)} µL"
                                 f"{channels}): {tips[spec.name]} tip{'s' if tips[spec.name] != 1 else ''}")
            lines.append("")
        if plan.modules:
            lines += ["**Instruments**", ""]
            for module in plan.modules.values():
                installed = profile.module(module.kind)
                what = installed.model if installed else _MODULE_NAMES[module.kind]
                lines.append(f"- {what.capitalize()} (`{module.name}`)")
            lines.append("")
        lines += ["**Labware**", "", "| Label | Type | Notes |", "|---|---|---|"]
        for labware in plan.labware.values():
            lines.append(f"| `{labware.name}` | {self._labware_type(plan, profile, labware)} | {labware.description} |")
        return lines + [""]

    @staticmethod
    def _reagents(plan: Plan) -> List[str]:
        if not plan.contents:
            return []
        lines = ["## Reagents to prepare", "", "| Labware | Well | Liquid | Volume (µL) |", "|---|---|---|---|"]
        lines += [f"| `{c.well.labware}` | {c.well.well} | {c.liquid.name} | {format_number(c.volume)} |"
                  for c in plan.contents]
        return lines + [""]

    # --- steps -----------------------------------------------------------------------------

    def _step(self, plan: Plan, profile: RobotProfile, step: Step,
              transfer_plan: Optional[TransferPlan]) -> Optional[List[str]]:
        """Title followed by body lines, or ``None`` for steps a person doesn't need to do."""
        if isinstance(step, TransferSet):
            return self._transfer_step(plan, profile, step, transfer_plan)
        if isinstance(step, SetTemperature):
            module = self._module_name(plan, step.module)
            if step.celsius is None:
                return [f"Turn off the {module}"]
            return [f"Set the {module} to {step.celsius:g} °C"]
        if isinstance(step, SetLid):
            return None  # lid handling is part of loading and running the thermocycler
        if isinstance(step, ThermalProfile):
            return self._thermal_step(plan, step)
        if isinstance(step, MoveLabware):
            if step.destination == OFF_DECK:
                return [f"Set `{step.labware}` aside"]
            return [f"Place `{step.labware}` on the {self._module_name(plan, step.destination)}"]
        if isinstance(step, Delay):
            return [f"Wait {_duration(step.seconds)}"] + ([step.message] if step.message else [])
        if isinstance(step, Pause):
            return ["Pause", f"**{step.message}**"]
        if isinstance(step, Comment):
            return ["Note", step.text]
        return [type(step).__name__]

    def _transfer_step(self, plan: Plan, profile: RobotProfile, step: TransferSet,
                       transfer_plan: TransferPlan) -> List[str]:
        rows = self._rows(transfer_plan)
        pipettes = list(dict.fromkeys(row.pipette for row in rows))
        guidance = [f"Use the {' and '.join(f'**{p}**' for p in pipettes)}.", _TIP_POLICIES[step.tips]]
        note = profile.liquid_handling(step.liquid_class).get("note")
        if note:
            guidance.append(note)
        if step.ordering is Ordering.SEQUENTIAL:
            guidance.append("Do the transfers in the order listed.")
        table = ["| # | Tip | Pipette | From | To | Volume (µL) | Notes |", "|---|---|---|---|---|---|---|"]
        for number, row in enumerate(rows, 1):
            volume = row.volume_text or format_number(row.volume)
            if row.parts > 1:
                volume += f" ({row.parts} × {format_number(row.volume / row.parts)})"
            table.append(f"| {number} | {'new' if row.new_tip else ''} | {row.pipette} | {row.source} | {row.dest} "
                         f"| {volume} | {'; '.join(row.notes)} |")
        title = step.label or f"Transfer ({len(step.transfers)} transfers)"
        return [title, " ".join(guidance), ""] + table

    def _rows(self, transfer_plan: TransferPlan) -> List[_Row]:
        """Table rows from the planned operations, merging the parts of a split transfer into one row."""
        rows: List[_Row] = []
        new_tip = False
        reductions = {(w.well, w.when): w for w in transfer_plan.warnings}
        for op in transfer_plan.ops:
            if isinstance(op, PickUpTips):
                new_tip = True
            elif isinstance(op, TransferPass):
                if op.layout is HeadLayout.FIXED:
                    transfers = [op.transfers]
                else:
                    transfers = [[t] for t in op.transfers]
                for group in transfers:
                    first = group[0]
                    key = (op.pipette.name, tuple((t.source, t.dest) for t in group))
                    notes = self._notes(first, op, reductions=reductions)
                    if rows and rows[-1].key == key and not new_tip:
                        rows[-1].volume += first.volume
                        rows[-1].parts += 1
                        rows[-1].notes = list(dict.fromkeys(rows[-1].notes + notes))
                        continue
                    rows.append(_Row(new_tip, op.pipette.name, self._place(group, "source"), self._place(group, "dest"),
                                     first.volume, notes=notes, key=key))
                    new_tip = False
            elif isinstance(op, DistributePass):
                dests = ", ".join(self._place(list(d), "dest", short=i > 0) for i, d in enumerate(op.dispenses))
                volumes = {d[0].volume for d in op.dispenses}
                volume_text = f"{format_number(volumes.pop())} each" if len(volumes) == 1 else "see notes"
                extra = f", including {format_number(op.disposal_volume)} µL extra" if op.disposal_volume else ""
                notes = [f"aspirate {format_number(op.aspirate_volume)} µL once{extra}, then dispense into each well"]
                if op.disposal_volume:
                    notes.append("discard what is left")
                if len(volumes) > 1:
                    notes.append("volumes: " + ", ".join(format_number(d[0].volume) for d in op.dispenses))
                notes += self._notes(op.dispenses[0][0], op, include_mixing=False)
                rows.append(_Row(new_tip, op.pipette.name, self._place(list(op.dispenses[0]), "source"), dests,
                                 sum(d[0].volume for d in op.dispenses), notes=notes, volume_text=volume_text))
                new_tip = False
        return rows

    @staticmethod
    def _notes(transfer: Transfer, op, include_mixing: bool = True,
               reductions: Optional[Dict[Tuple[WellRef, str], MixReduced]] = None) -> List[str]:
        notes = []
        for when, mix, well in (("before", transfer.mix_before, transfer.source),
                                ("after", transfer.mix_after, transfer.dest)):
            if include_mixing and mix:
                note = f"mix {mix.repetitions} × {format_number(mix.volume)} µL {when}"
                reduced = (reductions or {}).get((well, when))
                if reduced:
                    note += (f" (reduced from {format_number(reduced.requested)} µL: "
                             f"the {reduced.pipette} holds {format_number(reduced.used)} µL)")
                notes.append(note)
        if transfer.dispense_below_top is not None:
            notes.append(f"dispense {format_number(transfer.dispense_below_top)} mm below the rim")
        if op.touch_tip:
            notes.append("touch the tip to the well wall")
        if op.layout is HeadLayout.FIXED:
            notes.append(f"{op.pipette.channels}-channel")
        return notes

    @staticmethod
    def _place(group: List[Transfer], end: str, short: bool = False) -> str:
        """``'`plate` A1'``, or the column for a multichannel group; *short* drops the labware name."""
        refs: List[WellRef] = [getattr(t, end) for t in group]
        first = refs[0]
        if len(set(refs)) == 1:
            where = first.well
        elif len(refs) == 8:
            where = f"column {first.column + 1}"
        else:
            where = f"{first.well}–{refs[-1].well}"
        return where if short else f"`{first.labware}` {where}"

    def _thermal_step(self, plan: Plan, step: ThermalProfile) -> List[str]:
        on_it = next((l.name for l in plan.labware.values() if l.module == step.module), None)
        title = step.label or "Run the thermocycler"
        lines = [title]
        load = f"Put `{on_it}` in the {self._module_name(plan, step.module)}" if on_it else \
            f"Use the {self._module_name(plan, step.module)}"
        lid = f" with the lid at {step.lid_celsius:g} °C" if step.lid_celsius is not None else ""
        lines.append(f"{load}, close the lid and run this program{lid}:")
        lines += ["", "| Temperature | Time |", "|---|---|"]
        lines += [f"| {s.celsius:g} °C | {_duration(s.seconds)} |" for s in step.steps]
        lines.append("")
        if step.repetitions > 1:
            lines.append(f"Repeat {step.repetitions} times (about {_duration(step.duration_seconds)} in total).")
        if step.hold_celsius is not None:
            lines.append(f"Then hold at {step.hold_celsius:g} °C.")
        return lines

    # --- helpers ---------------------------------------------------------------------------

    @staticmethod
    def _module_name(plan: Plan, name: str) -> str:
        module = plan.modules.get(name)
        return f"{_MODULE_NAMES[module.kind]} (`{name}`)" if module else f"`{name}`"

    @staticmethod
    def _labware_type(plan: Plan, profile: RobotProfile, labware: Labware) -> str:
        module = plan.modules.get(labware.module) if labware.module else None
        try:
            return profile.resolve_labware(labware, module.kind if module else None)
        except KeyError:
            return labware.format.name.replace("_", " ")


def _duration(seconds: float) -> str:
    """``90`` -> ``'1 min 30 s'``, ``3600`` -> ``'1 h'``."""
    seconds = round(seconds)
    hours, rest = divmod(seconds, 3600)
    minutes, secs = divmod(rest, 60)
    parts = [f"{hours} h"] * bool(hours) + [f"{minutes} min"] * bool(minutes) + [f"{secs} s"] * bool(secs)
    return " ".join(parts) or "0 s"
